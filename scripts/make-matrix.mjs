#!/usr/bin/env node
/**
 * Render `docs/MATRIX.md` from the capability registry, or check that the
 * committed file still matches it.
 *
 * The matrix is the published answer to "what works for which type", so it is
 * generated from the same table the reader uses (`src/types.js`) rather than
 * typed next to it. `--check` is what CI runs: a documentation edit that widens a
 * claim, or a code change that narrows a capability without saying so, fails
 * there instead of in a review comment three weeks later.
 *
 *     node scripts/make-matrix.mjs          # write docs/MATRIX.md
 *     node scripts/make-matrix.mjs --check  # fail if it differs
 *
 * Exit status: 0 when current, 1 when the file is stale (or missing).
 */

import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { CONTAINERS, OPERATIONS, RELEASED_TYPES, SERIALIZATIONS, SUPPORT, TYPES, TYPE_IDS, capabilityRows, describeType } from '../src/types.js';
import { draftEntry } from '../src/drafts.js';
import { FHGM_RULES, fhgmRuleCoverage } from '../src/fhgm.js';
import { provenance as releasedProvenance } from '../src/registry.js';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const TARGET = join(ROOT, 'docs', 'MATRIX.md');

/** Long prose becomes a numbered footnote, so the grids stay readable. */
const OPERATION_LABELS = {
  read: 'read the header',
  selectContract: 'select the contract',
  validateContract: 'validate against it',
  verifyChecksum: 'verify the checksum',
  verifyParentLinks: 'verify parent links',
  strip: 'strip the header',
  write: 'write a header',
};

const SHORT = {
  [SUPPORT.native]: 'yes',
  [SUPPORT.nativeDraft]: 'draft lane',
  [SUPPORT.notSupportedYet]: 'no',
  [SUPPORT.notApplicable]: 'n/a',
};

/**
 * @param {string} text
 * @returns {string}
 */
function anchor(text) {
  return text.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
}

const rows = capabilityRows();

/** Distinct reasons, in first-appearance order, each with an index. */
const reasons = [];
/** @type {Map<string, number>} */
const reasonIndex = new Map();
for (const row of rows) {
  if (row.reason === null) continue;
  if (!reasonIndex.has(row.reason)) {
    reasons.push(row.reason);
    reasonIndex.set(row.reason, reasons.length);
  }
}

/**
 * @param {object} row
 * @returns {string}
 */
function cellOf(row) {
  const label = SHORT[row.support];
  return row.reason === null ? label : `${label} [^${reasonIndex.get(row.reason)}]`;
}

const lines = [];
lines.push('# Capability matrix: five types, seven operations, six serializations');
lines.push('');
lines.push('Generated by `scripts/make-matrix.mjs` from `src/types.js`, `src/drafts.js` and the');
lines.push('provenance files. Do not edit the grids: edit the tables they come from, then run');
lines.push('`npm run matrix`. CI runs `npm run check:matrix`, which fails when this file and the');
lines.push('code disagree in either direction - a claim the code does not support, or a');
lines.push('capability the code has and the documentation does not mention.');
lines.push('');
lines.push(`The registry renders ${rows.length} cells (${TYPE_IDS.length} types x ${OPERATIONS.length} operations x ${SERIALIZATIONS.length} serializations) and ${reasons.length} distinct reasons.`);
lines.push('');
lines.push('Baseline: FAIR-bioHeaders-Specification ' + releasedProvenance.current + ' - ' + RELEASED_TYPES.map((type) => `${type} '${releasedProvenance.releases[releasedProvenance.current][type].schemaVersion}'`).join(', ') + '.');
lines.push('');
lines.push('## How to read a cell');
lines.push('');
lines.push('| Mark | Meaning |');
lines.push('| --- | --- |');
lines.push('| `yes` | implemented here, checked by the native test suite |');
lines.push('| `draft lane` | implemented here, but only where the caller passed `{drafts: [...]}`; the result is labelled draft and is never a released-contract result |');
lines.push('| `no` | not implemented: `not-supported-yet`, with the reason in the footnote |');
lines.push('| `n/a` | the cell is not a gap: the dimension does not apply to that type or serialization, and the footnote says who owns it |');
lines.push('');
lines.push('A footnote number repeats wherever the same reason applies. The full text of every');
lines.push('reason is at the end of this file.');
lines.push('');

// --- one grid per type -----------------------------------------------------
lines.push('## The grids');
lines.push('');
for (const typeId of TYPE_IDS) {
  const type = TYPES[typeId];
  lines.push(`### ${typeId} - ${type.status}${type.shape === 'nested-records' ? ', nested records inside an FHGFF3 header' : ''}`);
  lines.push('');
  lines.push('```text');
  lines.push(describeType(typeId));
  lines.push('```');
  lines.push('');
  const header = `| operation \\ serialization | ${SERIALIZATIONS.join(' | ')} |`;
  lines.push(header);
  lines.push(`| --- |${SERIALIZATIONS.map(() => ' --- |').join('')}`);
  for (const operation of OPERATIONS) {
    const cells = SERIALIZATIONS.map((serialization) => cellOf(rows.find((row) => row.type === typeId && row.operation === operation && row.serialization === serialization)));
    lines.push(`| ${OPERATION_LABELS[operation]} | ${cells.join(' | ')} |`);
  }
  lines.push('');
  if (type.status === 'released') {
    const versions = type.contracts.map((row) => `${row.release} = '${row.schemaVersion}'`).join(', ');
    lines.push('Contracts bundled (from `schemas/provenance.json`): ' + versions + '.');
  } else {
    const entry = draftEntry(typeId);
    lines.push('No contract, no registry row, no `schemaVersion` claim and no w3id URL. Read only through the');
    lines.push(`V7 lane against ${entry.repository} at ${entry.commit} (sha256 \`${entry.sha256}\`).`);
  }
  lines.push('');
}

// --- the version dimension -------------------------------------------------
lines.push('## Contract versions this build can select');
lines.push('');
lines.push('Selection is by the record\'s own `schema` citation under V1 to V6; a release with no');
lines.push('vendored copy is reported `unsupported-version` and is never checked against a');
lines.push('different contract (V4). Drafts appear here only as pins, because they have no');
lines.push('release to name.');
lines.push('');
lines.push('| type | status | release | `schemaVersion` | copy here | selected by |');
lines.push('| --- | --- | --- | --- | --- | --- |');
for (const typeId of TYPE_IDS) {
  const type = TYPES[typeId];
  if (type.status === 'released') {
    for (const contract of type.contracts) {
      const how = contract.release === releasedProvenance.current ? 'V1 (raw main), V2 (raw tag), V3 (w3id)' : 'V2 (raw tag), V3 (w3id)';
      lines.push(`| ${typeId} | released | ${contract.release} | '${contract.schemaVersion}' | \`schemas/${contract.file}\` | ${how} |`);
    }
  } else {
    const entry = draftEntry(typeId);
    lines.push(`| ${typeId} | draft | none - a draft takes no release form | none published | \`drafts/${entry.file}\` | V7, only with an explicit \`{drafts: [...]}\` |`);
  }
}
lines.push('');
lines.push(`The FHR 1 compatibility path (V6) reads a raw-main citation with \`schemaVersion\` the`);
lines.push(`number 1 against \`schemas/${releasedProvenance.releases[releasedProvenance.fhr1Release].FHR.file}\`, ${releasedProvenance.fhr1Release}, with a deprecation warning.`);
lines.push('');

// --- rules the drafts add --------------------------------------------------
lines.push('## Draft-lane rules, by name');
lines.push('');
lines.push('FHT\'s rules are C1 to C3 and FHGM\'s are B1 and K1 to K6, drafted in their own');
lines.push('repositories.');
lines.push('');
const fhtPin = draftEntry('FHT');
if (fhtPin.suiteCommit !== null && fhtPin.suiteManifestSha256 !== null) {
  lines.push('The lane reads two pinned things and they are separate claims: the contract bytes at');
  lines.push(`\`${fhtPin.commit}\` (sha256 \`${fhtPin.sha256.slice(0, 16)}…\`), and the development suite this`);
  lines.push(`build verifies at \`${fhtPin.suiteCommit}\` - manifest \`${fhtPin.suiteManifest}\`, sha256`);
  lines.push(`\`${fhtPin.suiteManifestSha256.slice(0, 16)}…\`, ${fhtPin.suiteVectors} vectors across ${fhtPin.suiteManifestBytes} bytes, whose ${(fhtPin.suiteRules ?? []).length} contract`);
  lines.push(`rules carry the ${(fhtPin.suiteRules ?? []).join('/')} ids listed below. The guard is`);
  lines.push('`scripts/ci/suite-pin.mjs`, and it refuses any other suite revision, so no draft');
  lines.push('count in this repository is attributed to a revision that was never checked.');
  if (fhtPin.commit === fhtPin.suiteCommit) {
    lines.push('(The two values above are the same commit by design: the 2026-11-18 re-pin found one');
    lines.push('commit that last touched both files, and the registry repeats it so the check is');
    lines.push('uniform - two fields, two claims, one revision.)');
  }
  lines.push('The re-pin of 2026-11-18 moved the contract bytes themselves for the first time: the');
  lines.push('pinned contract grew `mixed` to a fifth `MoleculeType` value, made `properties.schema` a');
  lines.push('const admitting only the raw-main citation while the type is a draft, and made the');
  lines.push('remaining patterns dialect-portable (FHT-Specification#54); contract and suite were');
  lines.push('re-pinned together because the new suite cannot be scored against the old bytes.');
} else {
  lines.push('No FHT suite pin is stated, so this build names no suite revision for FHT and no');
  lines.push('draft count here may claim one.');
}
const fhgmPin = draftEntry('FHGM');
if (fhgmPin.suiteCommit !== null && fhgmPin.suiteManifestSha256 !== null) {
  lines.push('');
  lines.push('FHGM is the same shape, over three artifacts: the record contract at');
  lines.push(`\`${fhgmPin.commit}\` (sha256 \`${fhgmPin.sha256.slice(0, 16)}…\`), the transport overlay beside it at`);
  lines.push(`\`${fhgmPin.overlay?.commit}\` (sha256 \`${fhgmPin.overlay?.sha256.slice(0, 16)}…\`), and the suite`);
  lines.push(`this build verifies at \`${fhgmPin.suiteCommit}\` - manifest`);
  lines.push(`\`${fhgmPin.suiteManifest}\`, sha256 \`${fhgmPin.suiteManifestSha256.slice(0, 16)}…\`,`);
  lines.push(`${fhgmPin.suiteVectors} vectors across ${fhgmPin.suiteManifestBytes} bytes, labelled ${(fhgmPin.suiteRules ?? []).join('/')}. Before the`);
  lines.push('re-pin of 2026-11-16 this registry stated no suite revision for FHGM at all, so its');
  lines.push('draft-lane run could only print `UNPINNED`; the guard is the same one and it refuses');
  lines.push('any other suite bytes. That re-pin left the record contract where it was; the');
  lines.push('re-pin of 2026-11-18 moved all three FHGM byte sets together, and each of the three');
  lines.push('commit fields above was checked to name a revision at which its artifact is');
  lines.push('byte-identical to the owning repository\'s live main (git blob, not timestamp).');
  lines.push('');
  lines.push('Two semantics travel with these bytes that no digest diff and no vector count shows.');
  lines.push('FHGM-Specification#29 widened what a `layers.model` **pass** means: on top of the previous');
  lines.push('checks, a pass now additionally implies trimmed invisible-character-free text, an RFC 3986');
  lines.push('scheme with a real host for every link, non-blank deposits, NFC-unique identifiers, and a');
  lines.push('root-level gene target. A matrix that only prints pins would hide that behind identical');
  lines.push('rule ids, so it is stated here as a note; this build\'s current standing against it is');
  lines.push('measured and reported in `docs/CONFORMANCE.md`, not asserted in this generated file. And');
  lines.push('K4 still cannot abstain: FAIR-bioHeaders-Tools-JavaScript#11 records that a feature layer');
  lines.push('with no usable rows yields `reject` where the disagreement with gff3-validator is about an');
  lines.push('abstention, so pinning this suite means running a lane whose K4 abstention semantics are');
  lines.push('disputed upstream - a stated condition of the pin, not a settled fact about the draft.');
} else if (fhgmPin.suiteCommit === null) {
  lines.push('');
  lines.push('FHGM states no suite pin in `drafts/provenance.json`, so its draft-lane run is');
  lines.push('labelled `UNPINNED`: the numbers it prints describe the checkout it was handed,');
  lines.push('and this build makes no claim about which revision that was.');
}
lines.push('');
lines.push('Which of the rules run here, and which do not:');
lines.push('');
lines.push('| rule | type | here | what it covers, or why it does not run |');
lines.push('| --- | --- | --- | --- |');
lines.push('| C1 | FHT | yes | the parsed metadata validates against the pinned `fht.json` |');
lines.push('| C2 | FHT | yes | schema-URL closure, inside the pinned bytes: another type\'s URL or an arbitrary URL fails the contract and never selects FHT |');
lines.push('| C3 | FHT | yes | parent-link verdicts `checked-pass` / `checked-fail` / `unchecked`, against parent bytes the caller supplies; never assumed, never invented |');
lines.push('| B1 | FHGM | yes | the released FHGFF3 schema and the exact-byte checksum must hold before any model verdict exists; with them false the verdict is `not-checked` |');
lines.push('| K1 | FHGM | yes | transport: R15 admits extension fields from FHGFF3 1.1, and `x-fhgm-models` holds one or more records. `overlay: true` also applies the pinned transport overlay, which since FHGM-Specification#17 admits either released base as a closed pairing - v0.5.0 with 1.1, or v0.6.0 with 1.2 - and refuses a citation and version that contradict each other |');
lines.push('| K2 | FHGM | yes | every record validates against the pinned record contract (`modelId`, `modelVersion`, `featureId`, `reference` required, objects closed) |');
lines.push('| K3 | FHGM | yes | `modelId` unique within a snapshot; a shared id is ambiguous and rejects that snapshot, current or supplied predecessor |');
const k4 = fhgmRuleCoverage().boundaries.K4;
lines.push(`| K4 | FHGM | yes | ${k4.resolves}. ${k4.withoutFeatureLayer}. ${k4.unusableFeatureLayer}. ${k4.stillElsewhere} |`);
lines.push('| K5 | FHGM | yes | a record reference shares at least one comparable form with the file genome link and never contradicts it |');
lines.push('| K6 | FHGM | yes | predecessor verdicts `resolvable` / `unresolvable` / `ambiguous`, against explicitly supplied prior snapshots only |');
lines.push('');
lines.push(`The rule ids this module knows are ${FHGM_RULES.join(', ')}; the ones that run are ${fhgmRuleCoverage().implemented.join(', ')}.`);
lines.push('');

// --- what a reading looks like --------------------------------------------
lines.push('## What a lane reading says');
lines.push('');
lines.push('A V7 reading is distinguishable from a released one in three places, all of them');
lines.push('machine-checkable (`test/draft-lane.test.mjs`):');
lines.push('');
lines.push('```json');
lines.push('{');
lines.push('  "schema": { "type": "FHT", "release": null, "schemaVersion": null, "rule": "V7" },');
lines.push('  "warnings": [');
lines.push(`    "${draftWarningText('FHT')}"`);
lines.push('  ]');
lines.push('}');
lines.push('```');
lines.push('');
lines.push('- `rule` is `V7`, not a release rule;');
lines.push('- `release` and `schemaVersion` are `null`, because a draft has taken neither form;');
lines.push('- the warning names the citation, the commit and the digest the bytes were read at.');
lines.push('');
lines.push('For FHGM there is no `schema` change to see, because the file is a released FHGFF3');
lines.push('file: its records are judged in a separate `fhgm` block, and the FHGFF3 result is');
lines.push('identical to what the same bytes produce with the lane shut');
lines.push('(`test/fhgm.test.mjs` asserts both halves of that).');
lines.push('');

// --- the shared suite, for context ----------------------------------------
lines.push('## The shared suite this matrix is measured against');
lines.push('');
const manifest = JSON.parse(readFileSync(join(ROOT, 'conformance', 'manifest.json'), 'utf8'));
const counts = {};
for (const vector of manifest.vectors) counts[vector.format] = (counts[vector.format] ?? 0) + 1;
lines.push(`Acceptance is the ${manifest.vectors.length} vectors of FAIR-bioHeaders-Specification's shared`);
lines.push('suite (`npm run conformance`). None of them is an FHT or FHGM vector - the shared');
lines.push('manifest publishes no draft contract, so V7 has no vector by design, and the two');
lines.push('draft types\' own suites stay in their own repositories and are run separately');
lines.push('(`node scripts/capability/draft-vectors.mjs`, labelled draft everywhere).');
lines.push('');
lines.push('| format | vectors | this build |');
lines.push('| --- | --- | --- |');
for (const [format, count] of Object.entries(counts).sort()) {
  const runnable = ['fasta', 'gfa', 'fhp-fasta', 'fhgff3'].includes(format);
  lines.push(`| ${format} | ${count} | ${runnable ? 'runnable: read, validate, verify checksum, strip' : 'not run: no reader for this serialization here'} |`);
}
lines.push('');

// --- footnotes -------------------------------------------------------------
lines.push('## Reasons, in full');
lines.push('');
reasons.forEach((reason, index) => {
  lines.push(`[^${index + 1}]: ${reason}`);
});
lines.push('');
lines.push(`Digest of this generated document: \`${createHash('sha256').update(reasons.join('\n') + rows.map((row) => `${row.type}/${row.operation}/${row.serialization}=${row.support}`).join('\n')).digest('hex').slice(0, 32)}\`.`);
lines.push('');

const rendered = `${lines.join('\n')}`;

/**
 * @param {string} type
 * @returns {string}
 */
function draftWarningText(type) {
  const entry = draftEntry(type);
  return `${entry.type}: warning: schema ${entry.citation} is an unreleased draft (commit ${entry.commit}, sha256 ${entry.sha256} of those bytes); read against that pinned draft, not a released schema`;
}

if (process.argv.includes('--check')) {
  if (!existsSync(TARGET)) {
    console.error('docs/MATRIX.md does not exist; run `npm run matrix`');
    process.exit(1);
  }
  const have = readFileSync(TARGET, 'utf8');
  if (have !== rendered) {
    const haveLines = have.split('\n').length;
    const wantLines = rendered.split('\n').length;
    console.error(`docs/MATRIX.md is stale: the committed file has ${haveLines} lines, the registry renders ${wantLines}.`);
    console.error('run `npm run matrix` and commit the result; the matrix is generated from src/types.js on purpose.');
    process.exit(1);
  }
  console.log(`docs/MATRIX.md matches the registry (${TYPE_IDS.length} types x ${OPERATIONS.length} operations x ${SERIALIZATIONS.length} serializations = ${rows.length} cells, ${CONTAINERS.length} containers)`);
} else {
  writeFileSync(TARGET, rendered);
  console.log(`wrote docs/MATRIX.md (${rows.length} cells, ${reasons.length} distinct reasons)`);
}
